#!/bin/sh
# Rebuild every eye style in firmware/eye/styles/ from art/, and the list of
# them. The order here is the order you swipe through on the pendant.
set -e
cd "$(dirname "$0")/.."
STYLES="hazel big_blue anime fizzgig snake_green demon doom-red skull hypno_red toonstripe doom-spiral spikes"
OUT=firmware/eye/styles
{
  echo "// Generated by tools/pack_all.sh. Do not edit."
  echo '#include "eye.h"'
  echo
  for s in $STYLES; do echo "extern const eye_style_t eye_style_$(echo "$s" | tr -c 'a-zA-Z0-9\n' '_');"; done
  echo
  echo "const eye_style_t *const eye_styles[] = {"
  for s in $STYLES; do echo "    &eye_style_$(echo "$s" | tr -c 'a-zA-Z0-9\n' '_'),"; done
  echo "};"
  echo "const int eye_style_count = sizeof(eye_styles) / sizeof(eye_styles[0]);"
} > $OUT/index.c
for s in $STYLES; do
  python3 tools/eyepack.py "art/$s" "$OUT/$(echo "$s" | tr -c 'a-zA-Z0-9\n' '_').c" --name "$s"
done
